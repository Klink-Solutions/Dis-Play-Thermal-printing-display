#!/usr/bin/env python3
"""Convert the 16x16 weather PNGs into a 1-bit C header (icons.h).

Usage: python3 make_icons.py ../../designer/icons ../weather_printer/icons.h
Each icon = 16 rows x 2 bytes, MSB = leftmost pixel, 1 = black.
Order must match the WeatherIcon enum in receipt.h.
"""
import sys
from PIL import Image

ORDER = [("clear", "ICON_CLEAR"), ("partly-cloudy", "ICON_PARTLY"), ("clouds", "ICON_CLOUDS"),
         ("rain", "ICON_RAIN"), ("snow", "ICON_SNOW"), ("thunderstorm", "ICON_THUNDER"),
         ("mist", "ICON_MIST")]

src, dst = sys.argv[1], sys.argv[2]
out = ["// Generated by tools/make_icons.py - do not edit by hand.",
       "#pragma once", "#include <stdint.h>", "#ifdef ARDUINO", "#include <pgmspace.h>", "#endif",
       "#ifndef PROGMEM", "#define PROGMEM", "#endif", "",
       "static const uint8_t WEATHER_ICONS[][32] PROGMEM = {"]
for name, label in ORDER:
    im = Image.open(f"{src}/{name}.png").convert("RGBA")
    assert im.size == (16, 16), name
    data = []
    for y in range(16):
        bits = 0
        for x in range(16):
            r, g, b, a = im.getpixel((x, y))
            if a > 128 and (r + g + b) / 3 < 200:
                bits |= 0x8000 >> x
        data += [bits >> 8, bits & 0xFF]
    out.append(f"  // {label}\n  {{" + ", ".join(f"0x{v:02X}" for v in data) + "},")
out.append("};")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst)
